var DashReaderPlugin = class extends import_obsidian6.Plugin {
  async onload() {
    await this.loadSettings();
    this.registerView(
      VIEW_TYPE_DASHREADER,
      (leaf) => new DashReaderView(leaf, this.settings)
    );
    this.addRibbonIcon("zap", "RSVP sidebar", () => {
      void this.activateView();
    });
    this.addRibbonIcon("scan", "RSVP fullscreen", () => {
      const text = this.getActiveTextOrSelection();
      if (!text) {
        new import_obsidian6.Notice("No text to read. Open a note or select text first.");
        return;
      }
      const plainText = MarkdownParser.parseToPlainText(text);
      if (!plainText || plainText.trim().length < 10) {
        new import_obsidian6.Notice("Text too short to read");
        return;
      }
      const timeoutManager = new TimeoutManager();
      const engine = new RSVPEngine(
        this.settings,
        () => {
        },
        // Will be overridden by modal
        () => {
        },
        // Will be overridden by modal
        timeoutManager
      );
      engine.setText(plainText);
      const modal = new FullscreenModal(
        this.app,
        engine,
        this.settings,
        () => {
          timeoutManager.clearAll();
        },
        timeoutManager
      );
      modal.open();
      engine.play();
    });
    this.addCommand({
      id: "open",
      name: "Open speed reader",
      callback: () => {
        void this.activateView();
      }
    });
    this.addCommand({
      id: "read-selection",
      name: "Read selected text",
      editorCallback: (editor) => {
        const selection = editor.getSelection();
        if (selection) {
          void this.activateView().then(() => {
            const view = this.getView();
            if (view) {
              view.loadText(selection);
            }
          });
        } else {
          new import_obsidian6.Notice("Please select some text first");
        }
      }
    });
    this.addCommand({
      id: "read-note",
      name: "Read entire note",
      callback: () => {
        const activeView = this.app.workspace.getActiveViewOfType(import_obsidian6.MarkdownView);
        if (activeView) {
          const content = activeView.editor.getValue();
          void this.activateView().then(() => {
            const view = this.getView();
            if (view) {
              view.loadText(content);
            }
          });
        } else {
          new import_obsidian6.Notice("No active note found");
        }
      }
    });
    this.addCommand({
      id: "read-fullscreen",
      name: "Read in fullscreen mode",
      callback: () => {
        const text = this.getActiveTextOrSelection();
        if (!text) {
          new import_obsidian6.Notice("No text to read. Open a note or select text first.");
          return;
        }
        const plainText = MarkdownParser.parseToPlainText(text);
        if (!plainText || plainText.trim().length < 10) {
          new import_obsidian6.Notice("Text too short to read");
          return;
        }
        const timeoutManager = new TimeoutManager();
        const engine = new RSVPEngine(
          this.settings,
          () => {
          },
          // Will be overridden by modal
          () => {
          },
          // Will be overridden by modal
          timeoutManager
        );
        engine.setText(plainText);
        const modal = new FullscreenModal(
          this.app,
          engine,
          this.settings,
          () => {
            timeoutManager.clearAll();
          },
          timeoutManager
        );
        modal.open();
        engine.play();
      }
    });
    this.addCommand({
      id: "toggle-play-pause",
      name: "Toggle play/pause",
      callback: () => {
        new import_obsidian6.Notice("Use Shift+Space key when speed reader is active");
      }
    });
    this.registerEvent(
      this.app.workspace.on("editor-menu", (menu, editor) => {
        const selection = editor.getSelection();
        if (selection) {
          menu.addItem((item) => {
            item.setTitle("Read with speed reader").setIcon("zap").onClick(() => {
              void this.activateView().then(() => {
                const view = this.getView();
                if (view) {
                  view.loadText(selection);
                }
              });
            });
          });
        }
      })
    );
    this.addSettingTab(new DashReaderSettingTab(this.app, this));
    this.registerEvent(
      this.app.workspace.on("layout-change", () => {
        const view = this.getView();
        if (view) {
          view.updateSettings(this.settings);
        }
      })
    );
  }
  onunload() {
  }
  getView() {
    const leaves = this.app.workspace.getLeavesOfType(VIEW_TYPE_DASHREADER);
    if (leaves.length > 0) {
      return leaves[0].view;
    }
    return null;
  }
  /**
   * Gets text from selection or active note
   * Prioritizes selection over full note content
   */
  getActiveTextOrSelection() {
    const activeView = this.app.workspace.getActiveViewOfType(import_obsidian6.MarkdownView);
    if (!activeView) {
      return null;
    }
    const editor = activeView.editor;
    const selection = editor.getSelection();
    if (selection && selection.trim().length > 0) {
      return selection;
    }
    const content = editor.getValue();
    if (content && content.trim().length > 0) {
      return content;
    }
    return null;
  }
  async loadSettings() {
    const rawSettings = await this.loadData();
    this.settings = validateSettings(rawSettings);
  }
  async saveSettings() {
    await this.saveData(this.settings);
    const view = this.getView();
    if (view) {
      view.updateSettings(this.settings);
    }
  }
  async activateView() {
    const { workspace } = this.app;
    let leaf = null;
    const leaves = workspace.getLeavesOfType(VIEW_TYPE_DASHREADER);
    if (leaves.length > 0) {
      leaf = leaves[0];
    } else {
      leaf = workspace.getRightLeaf(false);
      if (leaf) {
        await leaf.setViewState({
          type: VIEW_TYPE_DASHREADER,
          active: true
        });
      }
    }
    if (leaf) {
      void workspace.revealLeaf(leaf);
    }
  }
};
